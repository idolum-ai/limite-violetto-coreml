"""Experimental lookup for rounded GELU on the model's BF16 input lattice.

The table covers both signs, 2^-30 through 2^10. Outside this bounded grid
the current float-graph asymptotes are used. This does not implement NaN/Inf
or arbitrary non-BF16 inputs. Source values are generated by pinned Torch.
"""
import torch
import torch.nn.functional as F

class BF16Gelu(torch.nn.Module):
    def __init__(self):
        super().__init__()
        bits=torch.arange((127-30)*128,(127+10)*128+1,dtype=torch.int16)
        positive=bits.view(torch.bfloat16).float()
        values=torch.cat((positive,-positive))
        self.register_buffer('values',F.gelu(values).bfloat16().float())
        self.register_buffer('powers',2.**torch.arange(-30,11,dtype=torch.float32))
    def forward(self,x):
        magnitude=torch.clamp(x.abs(),min=2.**-30,max=2.**10)
        exponent=torch.floor(torch.log2(magnitude))
        power=self.powers[(exponent+30).long()]
        index=(exponent+30)*128+torch.round(magnitude/power*128)-128
        index=index+(x<0).float()*5121
        value=self.values[index.long()]
        return torch.where(x.abs()<2.**-30,x*.5,torch.where(x.abs()>1024,torch.where(x>0,x,torch.zeros_like(x)),value))
